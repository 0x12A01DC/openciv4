#!/usr/bin/env python3
"""Generates apps/oc4core/generated/IFaceStubs.h: a default implementation of every
pure virtual method of the SDK's engine interfaces (CvDLL*IFaceBase).

Each stub logs its first call through oc4::host::unimplemented() and returns a
value-initialised result, so the host can implement interfaces incrementally by
overriding methods of these classes. Void methods of the presentation interfaces
(graphics entities, symbols, UI) are silent no-ops instead: a headless engine has
nothing to show, so they are not missing functionality.

Usage: python tools/gen_iface_stubs.py   (run from anywhere; paths are relative to the repo)
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SDK = ROOT / "gamecore" / "CvGameCoreDLL"
OUT = ROOT / "apps" / "oc4core" / "generated" / "IFaceStubs.h"

HEADERS = [
    "CvDLLUtilityIFaceBase.h",
    "CvDLLEntityIFaceBase.h",
    "CvDLLInterfaceIFaceBase.h",
    "CvDLLEngineIFaceBase.h",
    "CvDLLIniParserIFaceBase.h",
    "CvDLLSymbolIFaceBase.h",
    "CvDLLPlotBuilderIFaceBase.h",
    "CvDLLFAStarIFaceBase.h",
    "CvDLLXMLIFaceBase.h",
    "CvDLLFlagEntityIFaceBase.h",
    "CvDLLPythonIFaceBase.h",
]

# Graphics and UI: void methods have nothing to do without a screen.
PRESENTATION = {
    "CvDLLEntityIFaceBase", "CvDLLInterfaceIFaceBase", "CvDLLEngineIFaceBase", "CvDLLSymbolIFaceBase",
    "CvDLLFeatureIFaceBase", "CvDLLRouteIFaceBase", "CvDLLRiverIFaceBase", "CvDLLPlotBuilderIFaceBase",
    "CvDLLFlagEntityIFaceBase",
}

METHOD = re.compile(
    r"virtual\s+(?P<ret>.+?)\s*\b(?P<name>[A-Za-z_]\w*)\s*\((?P<params>.*)\)\s*(?P<const>const)?\s*=\s*0$",
    re.S,
)


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def classes(text):
    """Yields (name, body) for every class definition."""
    for m in re.finditer(r"\bclass\s+(\w+)\s*(?::[^{;]*)?\{", text):
        depth, i = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        yield m.group(1), text[m.end():i - 1]


def split_params(params):
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out]


def strip_default(param):
    depth = 0
    for i, ch in enumerate(param):
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        elif ch == "=" and depth == 0:
            return param[:i].strip()
    return param


def stub(cls, decl):
    decl = decl[decl.index("virtual"):]  # drop access labels before the declaration
    m = METHOD.match(" ".join(decl.split()))
    if not m:
        return None
    ret, name = m.group("ret").strip(), m.group("name")
    params = ", ".join(strip_default(p) for p in split_params(m.group("params")))
    const = " const" if m.group("const") else ""
    what = f'"{cls}::{name}"'
    if ret == "void" and cls in PRESENTATION:
        body = "/* headless: nothing to present */"
    elif ret == "void":
        body = f"unimplemented({what});"
    elif ret.endswith("&"):
        body = f"unimplemented({what}); static std::remove_cvref_t<{ret}> s{{}}; return s;"
    else:
        body = f"unimplemented({what}); return {{}};"
    return f"\t{ret} {name}({params}){const} override {{ {body} }}"


def main():
    parts = [
        "#pragma once",
        "",
        "// Generated by tools/gen_iface_stubs.py from the SDK interface headers. Do not edit.",
        "// Default implementations of every engine interface method: log once, return {}.",
        "// Void graphics/UI methods are silent no-ops (nothing to present headless).",
        "",
        '#include "CvGameCoreDLL.h"',
    ]
    parts += [f'#include "{h}"' for h in HEADERS if h != "CvDLLUtilityIFaceBase.h"]
    parts += [
        '#include "Unimplemented.h"',
        "",
        "#include <type_traits>",
        "",
        "#pragma warning(push)",
        "#pragma warning(disable : 4100) // unreferenced parameter",
        "",
        "namespace oc4::host::stubs",
        "{",
    ]
    total = 0
    for header in HEADERS:
        text = strip_comments((SDK / header).read_text(encoding="latin-1"))
        for cls, body in classes(text):
            if not cls.startswith("CvDLL") or not cls.endswith("IFaceBase"):
                continue
            decls = [s.strip() for s in body.split(";") if "virtual" in s and re.search(r"=\s*0\s*$", s.strip())]
            methods = [s for s in (stub(cls, d) for d in decls) if s]
            if len(methods) != len(decls):
                raise SystemExit(f"{header}: could not parse {len(decls) - len(methods)} declarations in {cls}")
            short = cls[len("CvDLL"):-len("IFaceBase")]
            parts += [f"\t// {header}: {len(methods)} methods", f"\tclass {short}IFace : public {cls}", "\t{", "\tpublic:"]
            parts += ["\t" + m for m in methods]
            parts += ["\t};", ""]
            total += len(methods)
    parts += ["}", "", "#pragma warning(pop)", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {total} methods")


if __name__ == "__main__":
    main()
